"""Zephyr Scale Cloud client for importing test cases via CSV.

Uses the Zephyr Scale Cloud REST API v2:
https://support.smartbear.com/zephyr-scale-cloud/api-docs/

Authentication: a Zephyr Scale API token (generated in Jira → Apps → Zephyr Scale → API Keys).
This is different from your Jira API token.
"""
from __future__ import annotations

import os
from typing import Optional

import requests


_DEFAULT_BASE_URL = "https://api.zephyrscale.smartbear.com/v2"


def import_csv(
    csv_path: str,
    project_key: str,
    token: str,
    base_url: str = _DEFAULT_BASE_URL,
) -> dict:
    """Import a Zephyr Scale CSV file into a Jira project.

    Args:
        csv_path:    Path to the CSV file generated by the test-writer agent.
        project_key: Jira project key (e.g. "PST", "CAL").
        token:       Zephyr Scale API token (not the Jira token).
        base_url:    Zephyr Scale API base URL. Override for Server/DC.

    Returns:
        Parsed JSON response from the API (includes job progress URL).

    Raises:
        FileNotFoundError: If *csv_path* does not exist.
        requests.HTTPError: If the API returns an error status.
    """
    if not os.path.isfile(csv_path):
        raise FileNotFoundError(f"CSV file not found: {csv_path}")

    url = f"{base_url}/testcases/import/csv"
    headers = {"Authorization": f"Bearer {token}"}

    with open(csv_path, "rb") as csv_file:
        response = requests.post(
            url,
            headers=headers,
            data={"projectKey": project_key},
            files={"file": (os.path.basename(csv_path), csv_file, "text/csv")},
        )

    response.raise_for_status()
    return response.json()
